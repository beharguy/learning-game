const word = (text, emoji, page, clue = '') => ({ text, emoji, page, clue });
const question = (page, prompt, target, answers, extra = {}) => ({ page, prompt, target, answers, ...extra });
function add(id, start, end, title, subtitle, badge, color, questions, words = [], memory = []) {
  lessons.push({ id, start, end, title, subtitle, badge, color, questions, words, memory });
}
function sounds(page, rows, position = 'start') {
  return rows.map(([label, emoji, answer, ...others]) => question(page,
    position === 'start' ? 'מָה שׁוֹמְעִים בִּתְחִלַּת הַמִּלָּה?' : 'מָה שׁוֹמְעִים בְּסוֹף הַמִּלָּה?',
    answer, [answer, ...others], { label, emoji, audio: label, kind: 'sound', position,
      hint: position === 'start' ? `נַקְשִׁיב לַהַתְחָלָה: ${label}` : `נַקְשִׁיב לַסּוֹף: ${label}` }));
}
function shape(page, mark, others) {
  return question(page, 'אֵיפֹה הָאוֹת הַזֹּאת?', mark, [mark, ...others], { kind:'warmup', model: mark, hint: 'נִבְדֹּק אֶת הַצּוּרָה וְאֶת הַסִּימָן מִתַּחַת לָאוֹת.' });
}
function cloze(page, sentence, target, others, emoji = '✦') {
  return question(page, 'מָה מַתְאִים בַּמָּקוֹם הָרֵיק?', target, [target, ...others], { sentence, emoji, hint: 'נִקְרָא אֶת הַמִּשְׁפָּט שׁוּב.' });
}
function rhyme(page, label, target, others) {
  return question(page, 'מָה מִתְחָרֵז?', target, [target, ...others], { label, kind: 'rhyme', hint: 'נַקְשִׁיב לַצְּלִילִים בְּסוֹף הַמִּלִּים.' });
}
